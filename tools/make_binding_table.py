#!/usr/bin/env python3
"""Writes data/binding_energies.def: the binding energies of all electrons of the neutral atoms H .. Fm (Z = 1 .. 100), the
orbital data of collisional (impact) ionization (docs/specs/collisions.md, decision 94).

Source: the table bindingEnergy[] of Smilei 5.1, src/Ionization/IonizationTables.h (CeCILL-B licence; J. Derouillat et al.,
Comput. Phys. Commun. 222, 351 (2018)), which takes them from the atomic-data tables of the University of Guelph
(chembio.uoguelph.ca/educmat/atomdata/bindener/elecbind.htm). Electron k = 0 is the innermost (most bound), k = Z - 1 the
outermost. As in Smilei (and Perez et al., Phys. Plasmas 19, 083104 (2012)), the orbitals of the ion of charge Z* are these
neutral-atom energies shifted so that the outermost one equals the ionization energy I(Z*) (in VLPL: NIST ASD 5.12,
data/ionization_energies.def):  B_k(Z*) = I(Z*) - B_{Z-Z*-1} + B_k,  k = 0 .. Z - Z* - 1.

usage: python3 tools/make_binding_table.py <Smilei>/src/Ionization/IonizationTables.h > data/binding_energies.def
"""
import re
import sys

text = open(sys.argv[1]).read()
m = re.search(r"bindingEnergy\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
body = re.sub(r"/\*.*?\*/", " ", m.group(1))
vals = [float(x) for x in body.replace(",", " ").split()]
assert len(vals) == 100 * 101 // 2, len(vals)
print("// Binding energies [eV] of the electrons of the neutral atoms Z = 1 .. 100, k = 0 the innermost (generated by")
print("// tools/make_binding_table.py from Smilei 5.1, src/Ionization/IonizationTables.h, bindingEnergy[], CeCILL-B; data of the")
print("// University of Guelph atomic-data tables). X-macro data file, included by src/impact.cpp:  BINDING(Z, k, E [eV])")
o = 0
for Z in range(1, 101):
    for k in range(Z):
        print("BINDING(%d, %d, %.6g)" % (Z, k, vals[o]))
        o += 1
