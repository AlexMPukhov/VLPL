#!/usr/bin/env python3
"""Builds data/ionization_energies.def (decision 86) from two NIST downloads:

  curl -o nist_ie.csv  'https://physics.nist.gov/cgi-bin/ASD/ie.pl?spectra=H-Ds&submit=Retrieve+Data&units=1&format=2&order=0&at_num_out=on&sp_name_out=on&ion_charge_out=on&el_name_out=on&seq_out=on&shells_out=on&level_out=on&ion_conf_out=on&e_out=0&unc_out=on&biblio=on'
  curl -o nist_mass.txt 'https://physics.nist.gov/cgi-bin/Compositions/stand_alone.pl?ele=&all=all&ascii=ascii2&isotype=some'
  python3 tools/make_ionization_table.py nist_ie.csv nist_mass.txt RETRIEVED_DATE > data/ionization_energies.def

Energies: NIST Atomic Spectra Database, "Ground levels and ionization energies" (every charge state of H .. Ds). l of the
electron removed in k -> k + 1: the orbital of the last subshell of the ground configuration of the ion of charge k (NIST's
"Ground Shells"); where NIST gives none, the Madelung filling of the remaining electrons. Masses: NIST "Atomic Weights and
Isotopic Compositions": the standard atomic weight (the middle of an interval), [A] the mass number of the most stable
isotope, else the relative mass of the first listed isotope. NIST flags of the energies are kept in a comment per level:
(...) semi-empirical / interpolated, [...] theoretical.
"""
import csv
import re
import sys

ie_file, mass_file, date = sys.argv[1], sys.argv[2], sys.argv[3]
LETTER = {'s': 0, 'p': 1, 'd': 2, 'f': 3, 'g': 4}

def clean(x):
    x = x.strip()
    if x.startswith('="') and x.endswith('"'):
        x = x[2:-1]
    return x

rows = {}
sym = {}
with open(ie_file) as f:
    r = csv.reader(f)
    next(r)
    for row in r:
        if len(row) < 12:
            continue
        row = [clean(x) for x in row]
        try:
            Z, k = int(row[0]), int(row[2].replace('+', ''))
        except ValueError:
            continue
        e = re.sub(r'[^0-9.eE+-]', '', row[9])
        if not e:
            continue
        sym[Z] = row[1].split()[0]
        flag = (row[8] + row[10]).strip()
        rows.setdefault(Z, {})[k] = (e, row[5], flag)

def madelung_l(n_el):
    order = sorted([(n, l) for n in range(1, 8) for l in range(0, min(n, 4))], key=lambda t: (t[0] + t[1], t[0]))
    last = 0
    for n, l in order:
        if n_el <= 0:
            break
        last = l
        n_el -= 2 * (2 * l + 1)
    return last

def l_of(shells, Z, k):
    toks = [t for t in re.split(r'[.\s]', shells) if t and not t.startswith('[')]
    for t in reversed(toks):
        m = re.match(r'\d+([spdfg])', t)
        if m:
            return LETTER[m.group(1)]
    if shells.startswith('[') and not toks:          # a closed noble-gas core only: its last p shell (He: s)
        return 0 if shells == '[He]' else 1
    return madelung_l(Z - k)

mass = {}
txt = open(mass_file).read()
for blk in txt.split('Atomic Number = ')[1:]:
    Z = int(blk.split()[0])
    if Z in mass:
        continue
    m = re.search(r'Standard Atomic Weight = ([^\n]*)', blk)
    s = m.group(1).strip() if m else ''
    s = re.sub(r'<[^>]*>|&nbsp;', '', s)
    v = None
    if s.startswith('['):
        if ',' in s:
            a, b = s.strip('[]').split(',')
            v = 0.5 * (float(a) + float(b))
        else:
            v = float(s.strip('[]'))
    elif s:
        if ',' in s:
            a, b = s.split(',')
            v = 0.5 * (float(re.sub(r'\(.*', '', a)) + float(re.sub(r'\(.*', '', b)))
        else:
            v = float(re.sub(r'\(.*', '', s))
    if v is None:
        mm = re.search(r'Relative Atomic Mass = ([0-9.]+)', blk)
        v = float(mm.group(1))
    mass[Z] = v

print('''// Ionization energies of all charge states and the orbital quantum number l of the electron removed (decision 86,
// docs/specs/field_ionization.md). Generated by tools/make_ionization_table.py (queries there); X-macro data file, included by
// src/atomic.cpp and parsed by tools/ionization_ref.py:
//   ELEMENT(symbol, atomic number Z, atomic mass [u])
//   LEVEL(symbol, k, I_k [eV], l)   charge state k -> k + 1: the energy to remove one electron from the ground state of the ion
//                                   of charge +k, and the orbital quantum number l of that electron
// Energies: A. Kramida, Yu. Ralchenko, J. Reader and NIST ASD Team, NIST Atomic Spectra Database, "Ground levels and ionization
// energies", https://physics.nist.gov/asd (ver. 5.12), retrieved %s: every charge state of H .. Lr (Z = 1 .. 103; Rf .. Ds lack
// stages in the ASD and are left out). NIST brackets values that are not
// directly measured ((...) and [...]: theoretical, semi-empirical or interpolated, see the ASD notes); kept as a comment. Used as given.
// l: the last subshell of NIST's ground configuration of the ion of charge k (where none is given: Madelung filling).
// Masses: NIST "Atomic Weights and Isotopic Compositions" (standard atomic weight, the middle of an interval; [A] for elements
// without one: the mass number of the most stable isotope). Deuterium: hydrogen's energy (isotope shift ~4 meV), mass 2.014.''' % date)
for Z in sorted(rows):
    lev = rows[Z]
    if sorted(lev) != list(range(Z)):
        sys.stderr.write('skipped %s (Z = %d): %d of %d levels\n' % (sym[Z], Z, len(lev), Z))
        continue
    s = sym[Z]
    print('\nELEMENT(%s, %d, %.6g)' % (s, Z, mass[Z]))
    for k in range(Z):
        e, sh, flag = lev[k]
        print('LEVEL(%s, %d, %s, %d)%s' % (s, k, e, l_of(sh, Z, k), '   // ' + flag if flag in ('()', '[]') else ''))
    if Z == 1:
        print('\nELEMENT(D, 1, 2.014)\nLEVEL(D, 0, %s, 0)' % lev[0][0])
